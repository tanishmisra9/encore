import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';

const baseUrl = process.env.BASE_URL || 'https://encore.encore-tanishmisra9.workers.dev';
const outputDir = process.env.RECORDING_DIR || '/tmp/encore-demo-recording';
await mkdir(outputDir, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, recordVideo: { dir: outputDir, size: { width: 1280, height: 720 } } });
const page = await context.newPage();
await page.goto(baseUrl + '/', { waitUntil: 'networkidle' });
await page.waitForTimeout(Number(process.env.HOME_MS || 42000));
await page.goto(baseUrl + '/demo.html', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Start the Friday-night plan' }).click();
await page.getByRole('heading', { name: 'Places where the night can meet.' }).waitFor();
await page.locator('.demo-option').first().getByRole('button', { name: /Choose this/ }).click();
await page.waitForTimeout(Number(process.env.VOTE_MS || 2500));
await page.getByRole('button', { name: 'Replan around that' }).click();
await page.waitForTimeout(Number(process.env.REPLAN_MS || 5000));
const video = page.video();
await page.close(); await context.close(); await browser.close();
console.log(await video.path());
